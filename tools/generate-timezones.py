#!/usr/bin/env python3
"""Regenerate web/js/timezones.js: IANA zone name -> POSIX TZ string (#371).

The device has no zoneinfo database, so the picker sends the POSIX string
that sits at the end of each TZif file. Zones come from tzdata's zone.tab
(one or more per country) plus UTC. Angle-bracket names such as "<+04>-4"
are rewritten to LST/LDT exactly as src/timezone.h does, because the
initramfs only exports letters, digits and "+-:,./" as TZ.

Usage: python3 tools/generate-timezones.py [/usr/share/zoneinfo] > web/js/timezones.js
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo')
VALID = re.compile(r'^[A-Za-z0-9+\-:,./]{1,63}$')


def footer(path):
    data = path.read_bytes()
    if not data.startswith(b'TZif') or data[4:5] not in (b'2', b'3', b'4'):
        raise SystemExit(f'{path}: not a TZif v2+ file')
    line = data.rstrip(b'\n').rsplit(b'\n', 1)[-1].decode('ascii')
    return line


def normalize(tz):
    names = iter(('LST', 'LDT'))
    out = re.sub(r'<[A-Za-z0-9+\-]+>', lambda _m: next(names), tz)
    if not VALID.match(out):
        raise SystemExit(f'unusable POSIX TZ {tz!r}')
    return out


def main():
    version = 'unknown'
    zi = ROOT / 'tzdata.zi'
    if zi.exists():
        first = zi.read_text().splitlines()[0]
        if first.startswith('# version '):
            version = first[len('# version '):]
    names = {'UTC'}
    for line in (ROOT / 'zone.tab').read_text().splitlines():
        if line and not line.startswith('#'):
            names.add(line.split('\t')[2])
    rows = []
    for name in sorted(names):
        tz = footer(ROOT / name)
        if not tz:
            raise SystemExit(f'{name}: TZif file has no POSIX footer')
        rows.append((name, normalize(tz)))
    print('/* Generated by tools/generate-timezones.py from tzdata %s; do not edit by hand. */' % version)
    print('/* IANA name -> POSIX TZ string the device stores (#371). <...> names are written as LST/LDT. */')
    print('window.LE_TIMEZONES=[')
    print(',\n'.join('[%s,%s]' % (repr_js(n), repr_js(t)) for n, t in rows))
    print('];')


def repr_js(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


if __name__ == '__main__':
    main()
